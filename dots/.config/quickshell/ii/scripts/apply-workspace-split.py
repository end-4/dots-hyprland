#!/usr/bin/env python3
"""Apply N-monitor workspace split live in Hyprland and persist to ~/.config/hypr/workspaces.lua."""

import json
import os
import subprocess
import sys

WORKSPACES_LUA = os.path.expanduser("~/.config/hypr/workspaces.lua")
TOTAL_WORKSPACES = 10


def hyprctl_json(args: list[str]):
    out = subprocess.check_output(["hyprctl", *args, "-j"], text=True)
    return json.loads(out)


def parse_splits(arg: str, num_monitors: int) -> list[int]:
    arg = arg.strip()
    if arg in ("", "0"):
        return []
    parts = [max(1, min(TOTAL_WORKSPACES - 1, int(float(p)))) for p in arg.split(",") if p.strip()]
    needed = num_monitors - 1
    if len(parts) != needed:
        # Evenly distribute across num_monitors
        parts = [round(TOTAL_WORKSPACES * (i + 1) / num_monitors) for i in range(needed)]
    # Enforce strictly increasing boundaries: 1 <= b_0 < b_1 < ... <= 9
    for i in range(needed):
        min_v = i + 1
        max_v = TOTAL_WORKSPACES - (needed - i)
        parts[i] = max(min_v, min(max_v, parts[i]))
        if i > 0 and parts[i] <= parts[i - 1]:
            parts[i] = min(max_v, parts[i - 1] + 1)
    return parts


def monitor_for_workspace(wid: int, monitors: list[dict], splits: list[int]) -> str:
    for idx, boundary in enumerate(splits):
        if wid <= boundary:
            return monitors[idx]["name"]
    return monitors[-1]["name"]


def main() -> int:
    if len(sys.argv) < 2:
        return 1

    monitors = hyprctl_json(["monitors"])
    if len(monitors) < 2:
        return 0

    order = []
    cfg_path = os.path.expanduser("~/.config/illogical-impulse/config.json")
    try:
        with open(cfg_path, encoding="utf-8") as f:
            order = json.load(f).get("background", {}).get("monitorOrder", []) or []
    except Exception:
        order = []

    monitors.sort(key=lambda m: (
        order.index(m["name"]) if m["name"] in order else len(order),
        m.get("x", 0),
        m.get("id", 0),
    ))
    splits = parse_splits(sys.argv[1], len(monitors))

    # First workspace ID for each monitor (gets default = true)
    first_ws = {1}
    for b in splits:
        first_ws.add(b + 1)

    # Persist to ~/.config/hypr/workspaces.lua (sourced automatically by hyprland.lua)
    lines = ["-- Auto-generated by Quickshell Monitor Workspace Split\n"]
    if not splits:
        lines.append("-- Shared workspaces (unpinned)\n")
    else:
        for i in range(1, TOTAL_WORKSPACES + 1):
            mon = monitor_for_workspace(i, monitors, splits)
            if i in first_ws:
                lines.append(f'hl.workspace_rule({{ workspace = "{i}", monitor = "{mon}", default = true }})\n')
            else:
                lines.append(f'hl.workspace_rule({{ workspace = "{i}", monitor = "{mon}" }})\n')

    os.makedirs(os.path.dirname(WORKSPACES_LUA), exist_ok=True)
    with open(WORKSPACES_LUA, "w", encoding="utf-8") as f:
        f.writelines(lines)

    subprocess.run(["hyprctl", "reload"], check=False)

    if splits:
        existing = hyprctl_json(["workspaces"])
        for ws in existing:
            wid = ws.get("id", -1)
            if 1 <= wid <= TOTAL_WORKSPACES:
                target = monitor_for_workspace(wid, monitors, splits)
                if ws.get("monitor") != target:
                    subprocess.run(
                        [
                            "hyprctl",
                            "dispatch",
                            f'hl.dsp.workspace.move({{ workspace = {wid}, monitor = "{target}" }})',
                        ],
                        check=False,
                    )

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
